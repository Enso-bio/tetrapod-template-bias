"""LaTeX macros for the post hoc analysis of amendment E6 (generated from result files; no hand-typed values)."""
import importlib
import json

from common import RESULTS

tables = importlib.import_module('11_paper_tables')
num, pval, OUT = tables.num, tables.pval, tables.OUT


def main():
    e = json.loads((RESULTS / 'E6_msa_platypus.json').read_text())
    off, ci, dif = e['primate_offset_SD'], e['primate_offset_ci95'], e['differences']
    m = {'SixGenesIn': f"{e['n_genes_input']:,}", 'SixGenes': f"{e['n_genes_retained']:,}",
         'SixPost': f"{e['mean_max_posterior']:.3f}"}
    for key, name in [('main', 'Msa'), ('human_sites', 'MsaHs'), ('E5_human', 'Hum'), ('E5_platypus', 'Pla')]:
        m[f'SixOff{name}'] = num(off[key], 2)
        m[f'SixOff{name}Lo'] = num(ci[key][0], 2)
        m[f'SixOff{name}Hi'] = num(ci[key][1], 2)
        m[f'SixRank{name}'] = e['human_rank_of_57'][key]
    for key, name in [('main_minus_E5_platypus', 'MsaPla'), ('main_minus_E5_human', 'MsaHum'),
                      ('human_sites_minus_main', 'HsMsa')]:
        m[f'SixDiff{name}'] = num(dif[key]['estimate'], 2)
        m[f'SixDiff{name}Lo'] = num(dif[key]['ci95'][0], 2)
        m[f'SixDiff{name}Hi'] = num(dif[key]['ci95'][1], 2)
    m['SixRPla'] = f"{e['r_with_E5']['E5_platypus']:.3f}"
    m['SixRHum'] = f"{e['r_with_E5']['E5_human']:.2f}"
    p1 = e['P1_main']
    m.update({'SixBeta': num(p1['beta']), 'SixLo': num(p1['ci95_low']), 'SixHi': num(p1['ci95_high']),
              'SixP': f"{p1['p_boot']:.2f}"})
    lines = ['% Generated by src/14_posthoc_tables.py (amendment E6, post hoc). Do not edit by hand.']
    lines += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in m.items()]
    (OUT / 'posthoc.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
