"""Collect figures, number macros and table macros from the two studies into paper/ (no hand-typed values).

Macros are prefixed to keep the studies apart: M = mammals (PROTEINAS_LONGEVIDAD), R = reptiles and amphibians
(LONGEVIDAD_REPTILES_ANFIBIOS). Run the generators of each study first (11_paper_tables.py and 10_paper_tables.py).
"""
import json
import re
import shutil
from pathlib import Path

from scipy.stats import norm

import build_methods_tables

HERE = Path(__file__).resolve().parent
SOURCES = {'M': HERE.parent / 'study1_mammals' / 'paper',
           'R': HERE.parent / 'study2_reptiles_amphibians' / 'paper'}
OUT = HERE / 'paper'


def main():
    (OUT / 'generated').mkdir(parents=True, exist_ok=True)
    for prefix, src in SOURCES.items():
        sub = OUT / 'figures' / ('mammals' if prefix == 'M' else 'ectotherms')
        sub.mkdir(parents=True, exist_ok=True)
        for f in (src / 'figures').glob('*.pdf'):
            shutil.copy2(f, sub / f.name)
        lines = []
        for f in sorted((src / 'generated').glob('*.tex')):
            text = f.read_text(encoding='utf-8')
            text = re.sub(r'\\newcommand\{\\([A-Za-z]+)\}', lambda m: f'\\newcommand{{\\{prefix}{m.group(1)}}}', text)
            lines.append(f'% from {f.relative_to(src.parent.parent)}\n{text}')
        (OUT / 'generated' / f'{prefix}_macros.tex').write_text('\n'.join(lines), encoding='utf-8')
    if (SOURCES['R'] / 'references.bib').exists():          # the repository ships the final references.bib
        shutil.copy2(SOURCES['R'] / 'references.bib', OUT / 'references.bib')
    percent_macros()
    build_methods_tables.main()
    print('inputs collected in', OUT)


def percent_macros():
    """Confidence limits of beta (log10 years per SD) expressed as % change in maximum lifespan per SD."""
    values = {}
    for prefix in SOURCES:
        text = (OUT / 'generated' / f'{prefix}_macros.tex').read_text(encoding='utf-8')
        for name, val in re.findall(r'\\newcommand\{\\([A-Za-z]+)\}\{([^{}%]*)\}', text):
            values[name] = val
    def pct(name):
        x = float(values[name].replace('$-$', '-'))
        p = 100 * (10 ** x - 1)
        return f'{p:+.0f}'.replace('-', '$-$')
    pairs = {'MPrimary': ('MPOneLo', 'MPOneHi'), 'MOpossum': ('MOpLo', 'MOpHi'), 'MPlatypus': ('MEcLo', 'MEcHi'),
             'RPrimary': ('RPOneLo', 'RPOneHi')}
    lines = ['% Generated by build_inputs.py: 95% CI of beta as % change in maximum lifespan per SD of the metric.']
    for key, (lo, hi) in pairs.items():
        lines.append(f'\\newcommand{{\\{key}PctLo}}{{{pct(lo)}\\%}}')
        lines.append(f'\\newcommand{{\\{key}PctHi}}{{{pct(hi)}\\%}}')
    # Minimum detectable effect (80% power) at the two-sided alpha of the primary tests (0.025), from the SE of beta
    z = norm.ppf(1 - 0.025 / 2) + norm.ppf(0.80)
    se = {'MOpDetectA': json.loads((SOURCES['M'].parent / 'results' / 'posthoc_monodelphis_domestica_template.json')
                                   .read_text())['P1_posthoc']['se'],
          'RDetectA': json.loads((SOURCES['R'].parent / 'results' / 'stats_summary.json').read_text())['P1']['se']}
    lines.append(f'\\newcommand{{\\PowerZ}}{{{z:.2f}}}')
    for key, s in se.items():
        lines.append(f'\\newcommand{{\\{key}}}{{{100 * (10 ** (z * s) - 1):.0f}}}')
    (OUT / 'generated' / 'pct_macros.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
