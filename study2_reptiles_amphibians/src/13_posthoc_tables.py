"""LaTeX macros for the post hoc analyses of amendment E2 (generated from result files; no hand-typed values)."""
import json
import importlib

from common import RESULTS

tables = importlib.import_module('10_paper_tables')
num, pval, OUT = tables.num, tables.pval, tables.OUT


def main():
    a = json.loads((RESULTS / 'posthoc_E2a_human_template.json').read_text())
    b = json.loads((RESULTS / 'posthoc_E2b_pergene_calibration.json').read_text())
    hu, zf = a['templates']['homo_sapiens'], a['templates']['zebrafish']
    m = {'PHHuBootP': f"{hu['bootstrap_lrt']['p_boot']:.3f}", 'PHZfBootP': f"{zf['bootstrap_lrt']['p_boot']:.2f}",
         'PHNullLambda': f"{hu['bootstrap_lrt']['null_lambda']:.2f}",
         'PHHuRRate': f"{hu['r_metric_log10_R']:.2f}", 'PHZfRRate': f"{zf['r_metric_log10_R']:.2f}",
         'PHDiffRRate': f"{a['human_minus_zebrafish_z']['r_with_log10_R']:.2f}"}
    for key, t in [('Hu', hu), ('Zf', zf)]:
        for name, label in [('clade_covariate', 'Clade'), ('adjusted_log10_R', 'Rate'), ('squamates_only', 'Sq'),
                            ('turtles_crocodilians_only', 'Arch')]:
            r = t[name]
            m[f'PH{key}{label}Beta'] = num(r['beta'])
            m[f'PH{key}{label}SE'] = f"{r['se']:.3f}"
            m[f'PH{key}{label}P'] = pval(r['p_wald'])
            m[f'PH{key}{label}N'] = r['n']
    for key, r in [('', b['lambda_ML']), ('Fix', b['lambda_fixed_null'])]:
        m[f'PHCal{key}Obs'] = r['observed_nominal']
        m[f'PHCal{key}Mean'] = f"{r['null_mean']:.0f}"
        m[f'PHCal{key}Lo'] = f"{r['null_interval95'][0]:.0f}"
        m[f'PHCal{key}Hi'] = f"{r['null_interval95'][1]:.0f}"
        m[f'PHCal{key}P'] = f"{r['p_calibrated_count']:.2f}"
        m[f'PHCal{key}FPR'] = f"{100 * r['null_false_positive_rate']:.1f}"
        m[f'PHCal{key}EmpGenes'] = r['genes_empirical_p_lt_0.05']
        m[f'PHCal{key}EmpQ'] = r['genes_empirical_q_lt_0.05']
    m['PHCalB'] = f"{b['B']:,}"
    m['PHCalLambdaZeroPct'] = f"{100 * b['observed_fraction_lambda_lt_0.05']:.0f}"
    m['PHCalNullModelLambda'] = f"{b['null_model']['lambda']:.2f}"
    lines = ['% Generated by src/13_posthoc_tables.py (amendment E2, post hoc). Do not edit by hand.']
    lines += [f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in m.items()]

    def row(label, r, p=None):
        lam = '--' if r.get('lambda') is None else f"{r['lambda']:.2f}"
        return (f"{label} & {r['n']} & {num(r['beta'])} & [{num(r['ci95_low'])}, {num(r['ci95_high'])}] & {lam} & "
                f"{p or pval(r['p_wald'])} \\\\")
    rows = []
    for key, t, name in [('homo_sapiens', hu, 'Human'), ('zebrafish', zf, 'Zebrafish')]:
        rows.append(f'\\multicolumn{{6}}{{@{{}}l}}{{\\textit{{{name} template}}}} \\\\')
        rows.append(row('All reptiles (Wald)', t['original_wald']))
        rows.append(row('All reptiles (bootstrap LRT)', t['bootstrap_lrt'], f"{t['bootstrap_lrt']['p_boot']:.3f}"))
        rows.append(row('Clade covariate', t['clade_covariate']))
        rows.append(row('Adjusted for log$_{10}$ divergence from ancestor', t['adjusted_log10_R']))
        rows.append(row('Squamates only', t['squamates_only']))
        rows.append(row('Turtles and crocodilians only', t['turtles_crocodilians_only']))
    lines.append('\\newcommand{\\PHTemplateRows}{%\n' + '\n'.join(rows) + '\n}')
    (OUT / 'posthoc.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
